"""Pack Blender's transparent casket renders into one bounded-size Godot texture."""
from pathlib import Path
import json
import math
import shutil

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'tmp/ch1-casket-render'
output = ROOT / 'assets/images/ch1_casket'
output.mkdir(parents=True, exist_ok=True)
metadata = json.loads((source / 'render.json').read_text(encoding='utf-8'))
frames = [Image.open(source / f'casket-{i:03}.png').convert('RGBA') for i in range(metadata['frame_count'])]
boxes = [frame.getbbox() for frame in frames]
crop = (min(b[0] for b in boxes) - 4, min(b[1] for b in boxes) - 4,
        max(b[2] for b in boxes) + 4, max(b[3] for b in boxes) + 4)
width, height = crop[2] - crop[0], crop[3] - crop[1]
columns = 7
rows = math.ceil(len(frames) / columns)
atlas = Image.new('RGBA', (width * columns, height * rows))
for i, frame in enumerate(frames):
    atlas.paste(frame.crop(crop), (i % columns * width, i // columns * height))
atlas.save(output / 'opening-atlas.png', optimize=True)
metadata.update({'columns': columns, 'cell': [width, height], 'crop': list(crop), 'origin': [320, 318]})
(output / 'opening.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding='utf-8')
descriptor = ROOT / 'scripts/data/casket_animation.gd'
descriptor.write_text('extends RefCounted\n## Generated by tools/pack_workshop_casket.py.\nconst DATA := ' + json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
blend = ROOT / 'art/ch1_casket'
blend.mkdir(parents=True, exist_ok=True)
shutil.copy2(source / 'workshop-casket.blend', blend / 'workshop-casket.blend')
print(json.dumps(metadata, indent=2))
print('Atlas:', atlas.size, 'RGBA memory:', round(atlas.width * atlas.height * 4 / 1024**2, 1), 'MiB')
