"""Cut the AI-painted celadon bowl into four jagged fragments for the restoration minigame.

Run:  python tools/build_fragments.py   (needs Pillow + NumPy)
Input:  assets/images/bowl.png  (transparent cut-out of the gpt-image-2 bowl)
Output: assets/images/bowl_broken.png, bowl_seams.png, frag_0..3.png and scripts/data/fragments_data.gd.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1] / 'assets/images'
rng = np.random.default_rng(42)
bowl = Image.open(ROOT / 'bowl.png').convert('RGBA')
W, H = bowl.size

# Rough fragment outlines in bowl-image pixels; edges are subdivided and jittered below.
OUTLINES = [
    [(0, 0), (215, 0), (200, 55), (222, 118), (120, 132), (40, 96), (0, 70)],          # rim, left
    [(440, 0), (640, 0), (640, 92), (590, 128), (500, 140), (452, 82)],                # rim, right
    [(105, 150), (205, 138), (262, 175), (255, 262), (170, 280), (120, 230)],          # body, lower left
    [(272, 62), (380, 52), (432, 110), (418, 205), (330, 222), (268, 168)],            # lotus centre (casket piece)
]


def jagged(points, step=14, amp=6):
    out = []
    for (x0, y0), (x1, y1) in zip(points, points[1:] + points[:1]):
        n = max(1, int(np.hypot(x1 - x0, y1 - y0) / step))
        nx, ny = -(y1 - y0), x1 - x0
        ln = np.hypot(nx, ny) or 1
        for k in range(n):
            t = k / n
            j = rng.uniform(-amp, amp) if k else 0
            out.append((x0 + (x1 - x0) * t + nx / ln * j, y0 + (y1 - y0) * t + ny / ln * j))
    return out


alpha = np.asarray(bowl.split()[3]).astype(float) / 255
rgb = np.asarray(bowl).astype(float)
hole = np.zeros((H, W), bool)
meta = []
polys = []
for i, outline in enumerate(OUTLINES):
    m = Image.new('L', (W, H), 0)
    jagged_pts = jagged(outline)
    polys.append(jagged_pts)
    ImageDraw.Draw(m).polygon(jagged_pts, fill=255)
    mask = (np.asarray(m) > 0) & (alpha > 0.5)
    hole |= mask
    ys, xs = np.nonzero(mask)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    piece = rgb.copy()
    piece[..., 3] = np.where(mask, rgb[..., 3], 0)
    # thin bright edge so the broken face reads as glaze over clay
    edge = mask & ~np.asarray(Image.fromarray(mask.astype('uint8') * 255).filter(ImageFilter.MinFilter(3))).astype(bool)
    piece[edge, :3] = piece[edge, :3] * 0.6 + np.array([226, 214, 186]) * 0.4
    Image.fromarray(piece[y0:y1, x0:x1].astype('uint8'), 'RGBA').save(ROOT / f'frag_{i}.png')
    poly = [(round(float(px), 1), round(float(py), 1)) for px, py in jagged_pts]
    meta.append({'center': [round((x0 + x1) / 2, 1), round((y0 + y1) / 2, 1)], 'size': [int(x1 - x0), int(y1 - y0)], 'poly': poly})

# Gold-seam overlay: fragment boundaries that lie inside the bowl (not on its outer silhouette).
inside = np.asarray(Image.fromarray((alpha > 0.5).astype('uint8') * 255).filter(ImageFilter.MinFilter(7))).astype(bool)
seam = np.zeros((H, W), bool)
labels = np.zeros((H, W), int)
for i, outline in enumerate(OUTLINES):
    m = Image.new('L', (W, H), 0)
    ImageDraw.Draw(m).polygon(polys[i], fill=255)
    mk = np.asarray(m) > 0
    edge = mk & ~np.asarray(Image.fromarray(mk.astype('uint8') * 255).filter(ImageFilter.MinFilter(3))).astype(bool)
    seam |= edge & inside
seam_img = Image.fromarray(seam.astype('uint8') * 255).filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(0.7))
sa = np.asarray(seam_img).astype(float)
out_rgba = np.zeros((H, W, 4), 'uint8')
out_rgba[..., :3] = 255
out_rgba[..., 3] = np.clip(sa * 1.6, 0, 255).astype('uint8')
Image.fromarray(out_rgba, 'RGBA').save(ROOT / 'bowl_seams.png')

broken = rgb.copy()
ring = np.asarray(Image.fromarray(hole.astype('uint8') * 255).filter(ImageFilter.MaxFilter(5))).astype(bool) & ~hole & (alpha > 0.5)
broken[hole] = [18, 30, 28, 110]           # dark translucent slot shows where pieces go
broken[ring, :3] = broken[ring, :3] * 0.45  # crack edge
Image.fromarray(broken.astype('uint8'), 'RGBA').save(ROOT / 'bowl_broken.png')
# Godot-readable constants for placement and gold-seam drawing
out = Path(__file__).resolve().parents[1] / 'scripts/data/fragments_data.gd'
lines = ['extends RefCounted', '## Generated by tools/build_fragments.py -- do not edit by hand.', f'const BOWL_SIZE := Vector2({W}, {H})', 'const FRAGMENTS := [']
for m in meta:
    lines.append(f"\t{{\"center\": Vector2({m['center'][0]}, {m['center'][1]}), \"size\": Vector2({m['size'][0]}, {m['size'][1]})}},")
lines.append(']')
out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('fragments:', [(m['center'], m['size']) for m in meta])
