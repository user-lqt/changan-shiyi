"""Chapter 3 (胡旋) music, drum SFX and note chart — built together so they stay in sync.

The tune follows the three-part form of a Tang 大曲: 散序 (free, slow, no dance),
中序 (steady beat, the dance begins) and 入破 (fast climax, endless spinning).
Mode: D Phrygian dominant (D Eb F# G A Bb C) for a Silk Road colour, over a D/A drone.

Outputs:
  assets/audio/huxuan.wav        backing track (no player drum part)
  assets/audio/hux_don.wav       jiegu drum centre hit
  assets/audio/hux_ka.wav        jiegu rim / stick click
  assets/audio/hux_cheer.wav     tavern crowd cheering
  scripts/data/huxuan_chart.gd   generated note chart (do not edit by hand)
Run: python -I tools/build_huxuan.py
"""
import sys
from pathlib import Path
import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from build_audio_lib import SR, save, tt, lowpass, highpass, reverb, zheng, bell, place  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
rng = np.random.default_rng(1710)

# ------------------------------------------------------------------ form and chart
# Chart strings: one char per subdivision of the bar (len 8 = eighth notes).
#   D = 咚 (drum centre)  K = 嗒 (rim)  lowercase = normal mode only (dropped in easy)
#   R = start of a roll (连打, the dancer spins), '-' = roll continues, '.' = rest
SECTIONS = [
    {"name": "散序", "bpm": 72, "bars": [
        "........", "D.......", "D...K...", "D...D...", "D...K.K.", "D.K.D...",
    ]},
    {"name": "中序", "bpm": 100, "bars": [
        "D...K...", "D.D.K...", "D...K.K.", "D.K.D.K.", "D.D.K.d.", "D...R---",
        "D.K.D.K.", "DkD.K.K.", "D.D.K.K.", "D.K.DDK.", "D.K.R---", "----D...",
    ]},
    {"name": "入破", "bpm": 132, "bars": [
        "D.DKD.K.", "D.DKDKK.", "DkDkD.K.", "D.K.R---", "--D.D.K.", "DDK.DDK.",
        "D.KkD.Kk", "DKDKR---", "----D.K.", "D.DKD.DK", "DkDkDKDK", "D.K.DDKK",
        "R-------", "----D.D.", "DKDKDKDK", "D.......",
    ]},
]
TAIL = 3.5


def build_timeline():
    notes = []
    starts = []
    t = 0.0
    roll = None
    for si, sec in enumerate(SECTIONS):
        beat = 60.0 / sec["bpm"]
        starts.append(round(t, 4))
        for bar in sec["bars"]:
            step = beat * 4 / len(bar)
            for i, c in enumerate(bar):
                at = t + i * step
                if c != "-" and roll is not None:
                    roll["d"] = round(at - roll["t"], 4)
                    notes.append(roll)
                    roll = None
                if c in "DdKk":
                    notes.append({"t": round(at, 4), "k": "don" if c in "Dd" else "ka", "d": 0.0,
                                  "easy": c.isupper(), "s": si})
                elif c == "R":
                    roll = {"t": round(at, 4), "k": "roll", "d": 0.0, "easy": True, "s": si}
            t += beat * 4
    if roll is not None:
        roll["d"] = round(t - roll["t"], 4)
        notes.append(roll)
    notes.sort(key=lambda n: n["t"])
    return notes, starts, t


NOTES, STARTS, END = build_timeline()


def write_chart():
    lines = ['extends RefCounted',
             '## GENERATED by tools/build_huxuan.py — edit the chart strings there, not here.',
             '## t = seconds, k = don / ka / roll, d = roll length, easy = kept in easy mode, s = section.',
             '',
             'const SECTIONS := %s' % [{"name": s["name"], "bpm": s["bpm"], "start": STARTS[i]} for i, s in enumerate(SECTIONS)],
             'const END := %.4f' % END,
             'const LENGTH := %.4f' % (END + TAIL),
             'const NOTES := [']
    for n in NOTES:
        lines.append('\t{"t": %.4f, "k": "%s", "d": %.4f, "easy": %s, "s": %d},' % (
            n["t"], n["k"], n["d"], "true" if n["easy"] else "false", n["s"]))
    lines.append(']')
    text = "\n".join(lines).replace("'", '"') + "\n"
    (ROOT / "scripts/data/huxuan_chart.gd").write_text(text, encoding="utf-8")


# ------------------------------------------------------------------ instruments
def midi(n):
    return 440.0 * 2 ** ((n - 69) / 12)


# D Phrygian dominant from D4 (62): D Eb F# G A Bb C
MODE = [0, 1, 4, 5, 7, 8, 10]


def deg(d, base=62):
    o, i = divmod(d, 7)
    return base + 12 * o + MODE[i]


def flute(freq, dur, gain=0.35):
    """Breathy bili / transverse flute: few partials, breath noise, delayed vibrato."""
    t = tt(dur)
    vib = 1 + 0.008 * np.sin(2 * np.pi * 5.5 * t) * np.clip((t - 0.15) / 0.3, 0, 1)
    ph = 2 * np.pi * np.cumsum(freq * vib) / SR
    y = np.sin(ph) + 0.35 * np.sin(2 * ph) + 0.12 * np.sin(3 * ph)
    breath = lowpass(rng.normal(0, 1, len(t)), 2500) * 0.25
    e = np.minimum(t / 0.06, 1) * np.clip((dur - t) / 0.08, 0, 1)
    return (y + breath * (0.4 + 0.6 * np.exp(-t * 6))) * e * gain


def drone(dur, gain=0.18):
    """D–A drone with a slow beating chorus, like a sheng or a sustained string."""
    t = tt(dur)
    y = np.zeros_like(t)
    for f, a in [(midi(38), 1.0), (midi(45), 0.7), (midi(50), 0.5)]:
        for detune in (-0.6, 0.6):
            y += a * (np.sin(2 * np.pi * (f + detune) * t) + 0.3 * np.sin(4 * np.pi * (f + detune) * t))
    swell = 0.75 + 0.25 * np.sin(2 * np.pi * t / 7.0)
    return lowpass(y, 900) * swell * gain


def frame_drum(gain=0.4):
    t = tt(0.35)
    body = np.sin(2 * np.pi * (85 + 40 * np.exp(-t * 25)) * t) * np.exp(-t * 10)
    skin = highpass(rng.normal(0, 1, len(t)), 400) * np.exp(-t * 40) * 0.25
    return (body + skin) * gain


def finger_cymbal(gain=0.15):
    return bell(2400, 0.9, gain) * 0.6


def jiegu_don():
    """羯鼓 centre: a tight, high-tuned two-headed drum, bright and dry."""
    t = tt(0.28)
    f = 190 + 120 * np.exp(-t * 40)
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 14)
    slap = highpass(rng.normal(0, 1, len(t)), 900) * np.exp(-t * 70) * 0.5
    return body + slap


def jiegu_ka():
    """羯鼓 played on the rim with the stick: a hard wooden click."""
    t = tt(0.12)
    y = np.sin(2 * np.pi * 1700 * t) * np.exp(-t * 80) + 0.6 * np.sin(2 * np.pi * 2900 * t) * np.exp(-t * 110)
    return y + highpass(rng.normal(0, 1, len(t)), 2500) * np.exp(-t * 200) * 0.6


def cheer(dur=2.6):
    """Crowd cheer: band-limited noise swells plus a few voice-like formant bursts."""
    t = tt(dur)
    crowd = lowpass(highpass(rng.normal(0, 1, len(t)), 300), 2600)
    shape = np.minimum(t / 0.25, 1) * np.exp(-np.maximum(t - 0.6, 0) * 1.6)
    y = crowd * shape
    for i in range(14):
        at = rng.uniform(0.05, 1.2)
        f0 = rng.uniform(220, 520)
        n = tt(rng.uniform(0.25, 0.5))
        v = np.sin(2 * np.pi * f0 * (1 + 0.15 * n) * n) * np.sin(np.pi * n / n[-1]) * 0.3
        place(y, v, at)
    return y


# ------------------------------------------------------------------ composition
MOTIFS = {
    # scale degrees (7 = octave D5), duration in beats
    "intro": [(0, 3), (1, 1), (2, 2), (1, 1), (0, 1), (4, 4), (3, 2), (2, 2), (1, 2), (0, 6)],
    "mid_a": [(4, 1), (5, 0.5), (4, 0.5), (3, 1), (2, 1), (3, 1), (4, 1), (2, 2)],
    "mid_b": [(2, 1), (3, 0.5), (4, 0.5), (5, 1), (6, 1), (7, 2), (6, 1), (4, 1)],
    "mid_c": [(4, 0.5), (3, 0.5), (2, 0.5), (1, 0.5), (2, 1), (0, 1), (1, 2), (0, 2)],
    "fast_a": [(7, 0.5), (6, 0.5), (7, 0.5), (8, 0.5), (7, 0.5), (6, 0.5), (4, 0.5), (5, 0.5)],
    "fast_b": [(4, 0.5), (5, 0.5), (6, 0.5), (7, 0.5), (8, 1), (7, 0.5), (6, 0.5)],
    "fast_c": [(9, 0.5), (8, 0.5), (7, 0.5), (6, 0.5), (5, 0.5), (4, 0.5), (2, 0.5), (1, 0.5)],
    "end": [(7, 2), (6, 1), (4, 1), (7, 4)],
}


def play_line(out, t0, beat, motif_names, voice, gain, base=62):
    t = t0
    for name in motif_names:
        for d, beats in MOTIFS[name]:
            dur = beats * beat
            f = midi(deg(d, base))
            place(out, voice(f, dur * 1.05, gain) if voice is flute else zheng(f, max(dur * 1.6, 0.6), gain, bright=1.4), t)
            t += dur
    return t


def build_music():
    n = int((END + TAIL) * SR)
    mel = np.zeros(n)
    acc = np.zeros(n)
    perc = np.zeros(n)
    acc += drone(END + TAIL)[:n]
    # 散序: free flute over the drone, sparse plucks.
    s0, b0 = STARTS[0], 60.0 / SECTIONS[0]["bpm"]
    play_line(mel, s0 + b0 * 0.5, b0, ["intro"], flute, 0.32)
    for k in range(0, len(SECTIONS[0]["bars"]) * 4, 4):
        place(acc, zheng(midi(50), 3.0, 0.25), s0 + k * b0)
    # 中序: pipa ostinato, frame drum on 1 and 3, cymbal on 4, flute melody.
    s1, b1 = STARTS[1], 60.0 / SECTIONS[1]["bpm"]
    bars1 = len(SECTIONS[1]["bars"])
    for bar in range(bars1):
        t = s1 + bar * 4 * b1
        for k, d in enumerate([0, 4, 7, 4, 2, 4, 7, 4]):
            place(acc, zheng(midi(deg(d, 50)), 0.7, 0.16, bright=1.8), t + k * b1 * 0.5)
        place(perc, frame_drum(0.35), t)
        place(perc, frame_drum(0.25), t + 2 * b1)
        place(perc, finger_cymbal(), t + 3 * b1)
    play_line(mel, s1, b1, ["mid_a", "mid_b", "mid_a", "mid_c"] * 3, flute, 0.28)
    # 入破: doubled tempo pipa tremolo, four-on-the-floor frame drum, high flute runs.
    s2, b2 = STARTS[2], 60.0 / SECTIONS[2]["bpm"]
    bars2 = len(SECTIONS[2]["bars"])
    for bar in range(bars2):
        t = s2 + bar * 4 * b2
        for k, d in enumerate([0, 7, 4, 7, 1, 7, 4, 7]):
            place(acc, zheng(midi(deg(d, 50)), 0.5, 0.17, bright=2.0), t + k * b2 * 0.5)
        for k in range(4):
            place(perc, frame_drum(0.38 if k % 2 == 0 else 0.26), t + k * b2)
        place(perc, finger_cymbal(0.12), t + 1.5 * b2)
        place(perc, finger_cymbal(0.12), t + 3.5 * b2)
    runs = ["fast_a", "fast_b", "fast_a", "fast_c"] * 3 + ["fast_a", "fast_b", "fast_c", "end"]
    play_line(mel, s2, b2, runs[: bars2], flute, 0.26)
    # Final bell.
    place(acc, bell(midi(62), 3.5, 0.5), END)
    mix = reverb(mel, 0.32, 1.8) [:n] * 1.0 + reverb(acc, 0.25, 1.4)[:n] * 0.9 + perc * 0.8
    fade = np.ones(n)
    fade[-int(1.2 * SR):] = np.linspace(1, 0, int(1.2 * SR))
    return mix * fade


if __name__ == "__main__":
    write_chart()
    save("hux_don", jiegu_don(), 0.9)
    save("hux_ka", jiegu_ka(), 0.8)
    save("hux_cheer", cheer(), 0.7)
    save("huxuan", build_music(), 0.85)
    print("NOTES", len(NOTES), "easy", sum(1 for x in NOTES if x["easy"]), "END %.2f" % END, "STARTS", STARTS)
